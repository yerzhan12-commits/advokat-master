module.exports = async (req, res) => {
  if (req.method !== 'POST') {
    res.status(405).json({ error: 'Method not allowed' });
    return;
  }

  const { caseId, messages, lang } = req.body || {};
  if (typeof caseId !== 'string' || !caseId.trim()) {
    res.status(400).json({ error: 'caseId is required' });
    return;
  }
  if (!Array.isArray(messages) || messages.length === 0) {
    res.status(400).json({ error: 'messages is required' });
    return;
  }

  const existingCase = await getCase(caseId);
  if (!existingCase) {
    res.status(404).json({ error: 'case not found' });
    return;
  }

  const langInstruction = LANG_INSTRUCTIONS[lang] || LANG_INSTRUCTIONS.ru;

  try {
    let parsed;

    if (process.env.MOCK_CASE_WIZARD === '1') {
      parsed = buildMockParsed(messages);
    } else {
      const client = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });

      const response = await client.messages.create({
        model: 'claude-sonnet-5',
        max_tokens: 8192,
        thinking: { type: 'disabled' },
        system: [
          {
            type: 'text',
            text: SYSTEM_PROMPT + '\n\n' + langInstruction,
            cache_control: { type: 'ephemeral' },
          },
        ],
        output_config: { format: { type: 'json_schema', schema: RESULT_SCHEMA } },
        messages,
      });

      const textBlock = response.content.find((b) => b.type === 'text');
      if (!textBlock) {
        res.status(502).json({ error: 'Модель не вернула текстовый ответ' });
        return;
      }

      try {
        parsed = JSON.parse(textBlock.text);
      } catch (parseErr) {
        console.error('case-wizard parse error:', parseErr, 'stop_reason:', response.stop_reason);
        res.status(502).json({
          error: response.stop_reason === 'max_tokens'
            ? 'Ответ получился слишком длинным и был обрезан. Попробуйте описать ситуацию покороче или повторите запрос.'
            : 'Не удалось разобрать ответ модели. Попробуйте ещё раз.',
        });
        return;
      }
    }

    if (parsed.status === 'done' && parsed.result) {
      // Госпошлина считается кодом от фактов, которые определила модель
      // (сумма иска, имущественный/нет), а не берётся из текста модели —
      // тот же принцип, что MRP-пороги в zhaloba-master/_lib/thresholds.js,
      // только здесь входные данные динамические (из разговора), а не константа.
      const gp = computeGosposhlina(parsed.result.claimAmountKzt, parsed.result.isPropertyClaim, process.env.MRP_KZT, parsed.result.isCriminalCase);
      parsed.result.gosposhlinaText = gp.text;

      try {
        await kv.lpush('case_wizard_log', JSON.stringify({
          ts: new Date().toISOString(),
          caseId,
          lang: lang === 'kk' ? 'kk' : 'ru',
          category: parsed.result.category,
        }));
      } catch (logErr) {
        console.error('case-wizard log error:', logErr);
      }

      try {
        const updated = { ...existingCase, messages, result: parsed.result, status: 'in_review' };
        await saveCase(caseId, updated);
      } catch (saveErr) {
        console.error('case save error:', saveErr);
        res.status(500).json({ error: 'Не удалось сохранить результат. Попробуйте ещё раз.' });
        return;
      }
    } else {
      // Промежуточный шаг интервью — тоже сохраняем messages, чтобы прогресс
      // не терялся при обрыве соединения на середине разговора.
      try {
        await saveCase(caseId, { ...existingCase, messages });
      } catch (saveErr) {
        console.error('case save (in-progress) error:', saveErr);
      }
    }

    res.status(200).json(parsed);
  } catch (err) {
    console.error('case-wizard error:', err);
    res.status(500).json({ error: err.message || 'internal error' });
  }
};

